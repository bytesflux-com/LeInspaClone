/**
 * Resolves services for any provider ID with fallback support.
 */
export function getMockProviderServices(providerId) {
  if (PROVIDER_SERVICES_DATA[providerId]) {
    return JSON.parse(JSON.stringify(PROVIDER_SERVICES_DATA[providerId]))
  }

  // Fallback to default Grace Njeri dataset
  return JSON.parse(JSON.stringify(PROVIDER_SERVICES_DATA['PR-82941']))
}

